from dataclasses import MISSING, asdict, dataclass, field, is_dataclass
from enum import Enum
import json
from pathlib import Path

import torch
from transformers import PretrainedConfig

from . import register_model_config


@dataclass(init=False)
class Gr00tN1d7Config(PretrainedConfig):
    """Unified configuration for Gr00tN1d7 model with backbone and action head.

    Gr00tN1d7 uses the Cosmos-Reason2-2B (Qwen3-VL architecture) VLM backbone,
    replacing the Eagle backbone used in Gr00tN1d6.
    """

    # Model identification
    model_type: str = "Gr00tN1d7"
    model_dtype: str = "bfloat16"  # Use bfloat16 for Flash Attention compatibility

    # Backbone configuration
    model_name: str = "nvidia/Cosmos-Reason2-2B"
    backbone_model_type: str = "qwen"
    model_revision: str | None = None
    tune_top_llm_layers: int = 0  # Number of top LLM layers to tune
    backbone_embedding_dim: int = 2048  # project_to_dim; must match Cosmos-Reason2-2B hidden size
    tune_llm: bool = False
    tune_visual: bool = False
    select_layer: int = 12
    reproject_vision: bool = False
    use_flash_attention: bool = True
    load_bf16: bool = False  # Enable BF16 loading
    backbone_trainable_params_fp32: bool = True

    ### Processing parameters
    image_crop_size: tuple[int, int] | None = (230, 230)
    image_target_size: tuple[int, int] | None = (256, 256)

    shortest_image_edge: int | None = None
    crop_fraction: float | None = None

    random_rotation_angle: int | None = None
    color_jitter_params: dict[str, float] | None = None
    use_albumentations_transforms: bool = True
    letter_box_transform: bool = False
    # Extra augmentation config (mask-based and others).
    extra_augmentation_config: dict | None = None
    formalize_language: bool = True
    apply_sincos_state_encoding: bool = (
        False  # Global flag to enable per-embodiment sin/cos encoding
    )
    use_percentiles: bool = True
    use_relative_action: bool = False

    # Action head configuration parameters
    max_state_dim: int = 132  # Default from state_shape
    max_action_dim: int = 132  # Default from action_shape
    action_horizon: int = 40
    hidden_size: int = 1024
    input_embedding_dim: int = 1536

    # State history: number of consecutive state timesteps fed to the state encoder
    state_history_length: int = 1

    # Global parameters
    add_pos_embed: bool = True
    attn_dropout: float = 0.2
    use_vlln: bool = True
    max_seq_len: int = 1024
    use_alternate_vl_dit: bool = True  # True for AlternateVLDiT, False for DiT
    attend_text_every_n_blocks: int = 2

    diffusion_model_cfg: dict = field(
        default_factory=lambda: {
            "positional_embeddings": None,
            "num_layers": 16,
            "num_attention_heads": 32,
            "attention_head_dim": 48,
            "norm_type": "ada_norm",
            "dropout": 0.2,
            "final_dropout": True,
            "output_dim": 1024,
            "interleave_self_attention": True,
        }
    )

    # Flow matching parameters
    num_inference_timesteps: int = 4
    noise_beta_alpha: float = 1.5
    noise_beta_beta: float = 1.0
    noise_s: float = 0.999
    num_timestep_buckets: int = 1000

    # Training parameters
    tune_projector: bool = True
    tune_diffusion_model: bool = True
    tune_vlln: bool = True

    # State augmentation parameters
    state_dropout_prob: float = 0.8  # State dropout probability
    exclude_state: bool = False  # Zero out all state inputs (ablation)
    use_mean_std: bool = False  # Use mean/std normalization instead of min/max

    # Multi-embodiment parameters
    geometry_mode: str = "off"
    """Geometry conditioning mode: ``off``, ``align`` (Spatial Forcing) or ``mix`` (3D-Mix).

    ``off`` adds no parameters and no compute. ``align`` supervises the backbone's image tokens
    against frozen geometry features and needs nothing at inference. ``mix`` gates those features
    onto the conditioning sequence and therefore runs the geometry encoder at inference too.
    """

    geometry_encoder_id: str = "depth-anything/Depth-Anything-V2-Small-hf"
    """Frozen geometry encoder. Depth-Anything-V2-Small is Apache-2.0; VGGT's released checkpoint is not."""

    geometry_align_loss_coeff: float = 0.5
    """Weight on the alignment loss when ``geometry_mode`` is ``align``.

    **Not a published value.** Spatial Forcing never states its weight factor, so this default is a
    guess kept only so a run starts. Sweep it rather than citing it.
    """

    geometry_align_position_embedding_std: float = 0.02
    """Initialisation scale of the target positional embedding when ``geometry_mode`` is ``align``.

    **Provisional, and measured to be weak.** Spatial Forcing credits this embedding with ten points
    on LIBERO-Long but publishes no scale. Against ``DA3METRIC-LARGE``'s layer-23 patch tokens
    (per-channel std 0.718 on a real ego_view frame) a std of 0.02 is 2.8% of the target's own
    scale, so the term starts weak and has to be learned up. Sweep it.
    """

    geometry_align_site: str = "post_vl_self_attention"
    """Where in the student the alignment loss is applied when ``geometry_mode`` is ``align``.

    One of ``post_vl_self_attention``, ``backbone_output``, or ``backbone_layer_<k>``.

    Spatial Forcing aligns layer 24 of 32 (0.75 depth) and its layer sweep is non-monotonic, with
    the half-depth point scoring worst. Every shipped N1.7 checkpoint truncates the 28-layer
    Cosmos-Reason2-2B language model at ``select_layer=16`` -- 0.57 depth -- and stacks ``vlln`` plus
    a four-layer self-attention transformer above it inside the action head. So
    ``post_vl_self_attention`` is the deepest reachable point and the closest analogue to upstream's
    choice, which is why it is the default; ``backbone_output`` is the raw truncation point, and
    ``backbone_layer_<k>`` reaches shallower layers for the sweep.
    """

    geometry_mix_tokens_as: str = "image"
    """Cross-attention branch the fused tokens join when ``geometry_mode`` is ``mix``."""

    max_num_embodiments: int = 32

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        for key, value in kwargs.items():
            setattr(self, key, value)

        # Ensures that all dataclass defaults (including those using default_factory)
        # are explicitly assigned to the instance, even if dataclasses initialization or subclassing
        # (PretrainedConfig) interferes with normal default injection.
        for f in self.__dataclass_fields__.values():
            if not hasattr(self, f.name):
                if f.default is not MISSING:
                    setattr(self, f.name, f.default)
                elif getattr(f, "default_factory", MISSING) is not MISSING:
                    setattr(self, f.name, f.default_factory())

    def to_filtered_dict(self, exclude_augment: bool = True) -> dict:
        """Return a dictionary representation of this config, optionally excluding augmentation keys."""
        if is_dataclass(self):
            cfg = asdict(self)
        else:
            cfg = dict(self.__dict__)

        if exclude_augment:
            exclude_keys = {
                "random_rotation_angle",
                "color_jitter_params",
                "use_albumentations_transforms",
                "formalize_language",
                "image_crop_size",
                "image_target_size",
                "shortest_image_edge",
                "crop_fraction",
            }
            cfg = {k: v for k, v in cfg.items() if k not in exclude_keys}

        return cfg

    def to_filtered_json(self, exclude_augment: bool = True, **kwargs) -> str:
        """Return a JSON string of this config, optionally excluding augmentation keys."""

        def default(o):
            if isinstance(o, (Path, torch.dtype, torch.device)):
                return str(o)
            if isinstance(o, Enum):
                return o.value
            return str(o)

        return json.dumps(
            self.to_filtered_dict(exclude_augment),
            indent=2,
            default=default,
            **kwargs,
        )


register_model_config("Gr00tN1d7", Gr00tN1d7Config)
